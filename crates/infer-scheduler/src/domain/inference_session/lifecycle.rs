/// A session at a specific lifecycle stage.
///
/// The type parameter `S: SessionState` is the state-specific data struct.
/// Different states expose different methods — enforced at compile time.
///
/// State diagram:
/// ```text
///   Queued ──start_prefill(kv)──▶ Prefilling ──promote_to_decoding──▶ Decoding
///                                       │                                │
///                                       └──────fail(msg)──────▶ Failed ◀┘
///                                                                ▲
///                                          Decoding ─finish(reason)── Finished
/// ```
///
/// **No `Queued::fail()`**: a queued session that fails (e.g. validation
/// reject) never had KV allocated, so it should be dropped from the
/// repository, not transitioned to `Failed`. This keeps `Failed::kv_alloc`
/// non-optional.
pub struct InferenceSession<S: SessionState> {
    /// Shared immutable metadata.
    pub meta: Arc<RequestMeta>,
    /// Response channel back to the HTTP server.
    pub handle: RequestHandle,
    /// State-specific data.
    pub state: S,
}

// ═══════════════════════════════════════════════════════════════════════════════
//  State Transitions — ownership transfer guarantees validity
// ═══════════════════════════════════════════════════════════════════════════════

impl InferenceSession<Queued> {
    /// Create a new queued session.
    pub fn new(meta: Arc<RequestMeta>, handle: RequestHandle) -> Self {
        Self {
            meta,
            handle,
            state: Queued { prefix_match: None },
        }
    }

    /// Set prefix match result.
    pub fn with_prefix_match(mut self, prefix_match: PrefixMatch) -> Self {
        self.state.prefix_match = Some(prefix_match);
        self
    }

    /// Transition: Queued → Prefilling.
    pub fn start_prefill(self, kv_lease: KvLease) -> InferenceSession<Prefilling> {
        let prompt_len = self.meta.input_ids.len();
        InferenceSession {
            meta: self.meta,
            handle: self.handle,
            state: Prefilling {
                kv_lease,
                num_computed_tokens: 0,
                inflight: None,
                prompt_len,
                prefill_start: Instant::now(),
            },
        }
    }

    /// Get the request ID.
    pub fn id(&self) -> &RequestId {
        &self.meta.id
    }
}

impl InferenceSession<Prefilling> {
    /// Transition: Prefilling → Decoding (when prefill is complete).
    pub fn start_decode(self) -> InferenceSession<Decoding> {
        debug_assert!(
            self.state.num_computed_tokens >= self.state.prompt_len,
            "start_decode called before prefill complete: {} < {}",
            self.state.num_computed_tokens,
            self.state.prompt_len,
        );
        InferenceSession {
            meta: self.meta,
            handle: self.handle,
            state: Decoding {
                kv_lease: self.state.kv_lease,
                output_tokens: Vec::new(),
                seq_position: self.state.prompt_len,
                prompt_len: self.state.prompt_len,
                first_token_time: Instant::now(),
                preemption_count: 0,
            },
        }
    }

    /// Transition: Prefilling → Failed (carries KV for cleanup).
    pub fn fail(self, message: String) -> InferenceSession<Failed> {
        InferenceSession {
            meta: self.meta,
            handle: self.handle,
            state: Failed {
                message,
                kv_lease: self.state.kv_lease,
                partial_output_tokens: Vec::new(),
            },
        }
    }

    /// Mark an in-flight segment as completed by the Worker.
    pub fn ack_inflight(&mut self) -> Option<InFlightPrefillSegment> {
        let inflight = self.state.inflight.take()?;
        self.state.num_computed_tokens = inflight.segment_end;
        Some(inflight)
    }

    /// Mark a segment as sent to Worker.
    pub fn set_inflight(&mut self, segment_start: usize, segment_end: usize) {
        self.state.inflight = Some(InFlightPrefillSegment {
            segment_start,
            segment_end,
            is_final: segment_end >= self.state.prompt_len,
        });
    }

    /// Whether this session has a segment in flight.
    pub fn has_inflight(&self) -> bool {
        self.state.inflight.is_some()
    }

    /// Advance: chunk completed, more to go.
    pub fn advance_chunk(&mut self, tokens_processed: usize) {
        self.state.num_computed_tokens += tokens_processed;
    }

    /// Check if prefill is complete.
    pub fn is_complete(&self) -> bool {
        self.state.num_computed_tokens >= self.state.prompt_len
    }

    /// Remaining tokens to prefill.
    pub fn remaining_tokens(&self) -> usize {
        self.state.prompt_len.saturating_sub(self.state.num_computed_tokens)
    }

    /// Get the request ID.
    pub fn id(&self) -> &RequestId {
        &self.meta.id
    }
}

impl InferenceSession<Decoding> {
    /// Transition: Decoding → Finished (carries KV for cleanup).
    pub fn finish(self, reason: FinishReason) -> InferenceSession<Finished> {
        let ttft = self.state.first_token_time.duration_since(self.meta.arrival_time);
        let e2e = self.meta.arrival_time.elapsed();
        let num_tokens = self.state.output_tokens.len() as u32;

        InferenceSession {
            meta: self.meta,
            handle: self.handle,
            state: Finished {
                finish_reason: reason,
                output_tokens: self.state.output_tokens,
                metrics: CompletionMetrics {
                    ttft,
                    e2e_latency: e2e,
                    num_output_tokens: num_tokens,
                    num_preemptions: self.state.preemption_count,
                },
                kv_lease: self.state.kv_lease,
            },
        }
    }

    /// Transition: Decoding → Failed (carries KV + partial output).
    pub fn fail(self, message: String) -> InferenceSession<Failed> {
        InferenceSession {
            meta: self.meta,
            handle: self.handle,
            state: Failed {
                message,
                kv_lease: self.state.kv_lease,
                partial_output_tokens: self.state.output_tokens,
            },
        }
    }

    /// Append a generated token.
    pub fn append_token(&mut self, token_id: i32) {
        self.state.output_tokens.push(token_id);
        self.state.seq_position += 1;
    }

    /// Number of tokens generated so far.
    pub fn num_generated(&self) -> usize {
        self.state.output_tokens.len()
    }

    /// Whether max_tokens has been reached.
    pub fn reached_max_tokens(&self) -> bool {
        self.state.output_tokens.len() >= self.meta.max_tokens
    }

    /// Preempt: Decoding → Queued (for recompute strategy).
    /// Returns the queued session and the lease (caller is responsible
    /// for releasing it back to the pool).
    pub fn preempt_recompute(self) -> (InferenceSession<Queued>, KvLease) {
        let kv_lease = self.state.kv_lease;
        let seq = InferenceSession {
            meta: self.meta,
            handle: self.handle,
            state: Queued { prefix_match: None },
        };
        (seq, kv_lease)
    }

    /// Preempt: Decoding → ResourceStarved (Phase 6 / plan §7).
    ///
    /// Used by the admission cascade when KV pressure forces the engine
    /// to evict a live decoder. Generated tokens are dropped; the prompt
    /// (in `Arc<RequestMeta>`) survives and the session can be lifted
    /// back into the waiting queue via [`InferenceSession::<ResourceStarved>::requeue`].
    ///
    /// Returns the new typed session and the legacy `KvLease`. In the
    /// new RadixTree-driven path the lease is empty (the worker-side
    /// indices have already been marked finished and will be reclaimed
    /// by the next `FreeKvIndices` round). In the legacy path the
    /// caller drops the lease, returning blocks to the block sink.
    pub fn preempt_to_starved(self) -> (InferenceSession<ResourceStarved>, KvLease) {
        let kv_lease = self.state.kv_lease;
        let dropped_output_count = self.state.output_tokens.len() as u32;
        let preemption_count = self.state.preemption_count + 1;
        let seq = InferenceSession {
            meta: self.meta,
            handle: self.handle,
            state: ResourceStarved {
                dropped_output_count,
                preemption_count,
            },
        };
        (seq, kv_lease)
    }

    /// Get the request ID.
    pub fn id(&self) -> &RequestId {
        &self.meta.id
    }
}

impl InferenceSession<ResourceStarved> {
    /// Lift a preempted session back into the waiting queue. The same
    /// `RequestMeta` (which holds the prompt) is preserved; preemption
    /// count is carried forward so policies can apply backoff.
    pub fn requeue(self) -> InferenceSession<Queued> {
        InferenceSession {
            meta: self.meta,
            handle: self.handle,
            // No prefix_match snapshot here; the next admission lookup
            // (driven by RadixTree::lookup_prefix in the new path) will
            // recompute it. The legacy field is `Option`-y for exactly
            // this reason.
            state: Queued { prefix_match: None },
        }
    }

    /// Number of output tokens that were dropped on preemption. Useful
    /// for metrics; the actual content is gone.
    pub fn dropped_output_count(&self) -> u32 {
        self.state.dropped_output_count
    }

    pub fn preemption_count(&self) -> u32 {
        self.state.preemption_count
    }

    pub fn id(&self) -> &RequestId {
        &self.meta.id
    }
}

impl InferenceSession<Finished> {
    /// Get the request ID.
    pub fn id(&self) -> &RequestId {
        &self.meta.id
    }
}

impl InferenceSession<Failed> {
    /// Get the request ID.
    pub fn id(&self) -> &RequestId {
        &self.meta.id
    }
}

// ═══════════════════════════════════════════════════════════════════════════════
//  AnySession — runtime enum for heterogeneous storage
// ═══════════════════════════════════════════════════════════════════════════════

/// Runtime wrapper for sessions in any active lifecycle state.
///
/// Repository code uses `AnySession` only for cancel/diagnostic paths; hot
/// transitions go through typed variants directly.
pub enum AnySession {
    Queued(InferenceSession<Queued>),
    Prefilling(InferenceSession<Prefilling>),
    Decoding(InferenceSession<Decoding>),
}

impl AnySession {
    /// Get the request ID regardless of state.
    pub fn id(&self) -> &RequestId {
        match self {
            Self::Queued(s) => &s.meta.id,
            Self::Prefilling(s) => &s.meta.id,
            Self::Decoding(s) => &s.meta.id,
        }
    }
}

// ═══════════════════════════════════════════════════════════════════════════════
//  Tests — typestate transition correctness
