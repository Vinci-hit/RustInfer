//! Type-state inference session lifecycle.
//!
//! A session is represented as `InferenceSession<S>` where `S` is one of the
//! sealed state types (`Queued` / `Prefilling` / `Decoding` / `Finished` /
//! `Failed`). State transitions consume the old value and produce a new type —
//! making invalid state access a compile-time error.
//!
//! ## Sealed trait
//!
//! `SessionState` is sealed: only the five state types in this module
//! implement it. External crates cannot extend the state machine, which keeps
//! the invariants centralized.

use std::sync::Arc;
use std::time::Instant;

use crate::domain::kv_cache_pool::KvLease;
use crate::infrastructure::kv_cache::traits::PrefixMatch;
use crate::domain::inference_session::handle::RequestHandle;
use infer_protocol::server_to_scheduler::DiffusionRequest;

